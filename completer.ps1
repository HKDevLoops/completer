# ============================================================================
# completer.ps1 - PowerShell-native modular completion manager.
# Native APIs only: Register-ArgumentCompleter, Set-PSReadLineKeyHandler,
# Set-Alias, Get-Command, Add-Content, Set-Content, Copy-Item, Get-Date,
# Out-String, Test-Path, New-Item.
#
# ZERO WORK AT LOAD: this file only DEFINES functions. Nothing probes, reads,
# writes or executes until you call `completer ...` explicitly.
#
# Dot-source once from your profile, then call:
#   completer <shell> [program...]     e.g. completer pwsh opencode git
#   completer list
#   completer alias add <name> <value>
#   completer alias remove <name>
#   completer update carapace
#   completer zoxide [shell...]
#
# Supported shells: pwsh, powershell, bash, zsh, fish, sh, nu, nushell, xonsh.
# PowerShell 5.1 compatible (no ??, no ternary, no 7-only operators).
# ============================================================================

function Get-CompleterSupportedShells {
    return @('pwsh','powershell','bash','zsh','fish','sh','nu','nushell','xonsh')
}

function Test-CompleterShell {
    param([string]$Shell)
    if (-not $Shell) { return $false }
    return ((Get-CompleterSupportedShells) -contains $Shell.ToLowerInvariant())
}

function Initialize-CompleterState {
    # Called only from entrypoints/functions - never at file load.
    $root = $env:COMPLETER_ROOT
    if (-not $root) { $root = $PSScriptRoot }
    if (-not $root) { $root = (Get-Location).Path }
    $script:CompleterRoot = $root
    $script:CompleterCompletions = Join-Path $root 'completions'
    $script:CompleterAliasFile = Join-Path $root 'alias.ps1'
}

function Ensure-CompleterState {
    if (-not $script:CompleterRoot -or -not $script:CompleterCompletions -or -not $script:CompleterAliasFile) {
        Initialize-CompleterState
    }
}

function Get-CompleterShellToken {
    param([string]$Shell)
    switch ($Shell.ToLowerInvariant()) {
        'pwsh'       { return 'powershell' }
        'powershell' { return 'powershell' }
        'nu'         { return 'nushell' }
        'nushell'    { return 'nushell' }
        default      { return $Shell.ToLowerInvariant() }
    }
}

function Get-CompleterExtension {
    param([string]$Shell)
    switch ($Shell.ToLowerInvariant()) {
        { $_ -eq 'pwsh' -or $_ -eq 'powershell' } { return 'ps1' }
        { $_ -eq 'nu' -or $_ -eq 'nushell' }      { return 'nu' }
        'xonsh' { return 'xsh' }
        'bash'  { return 'bash' }
        'zsh'   { return 'zsh' }
        'fish'  { return 'fish' }
        'sh'    { return 'sh' }
        default { return $Shell.ToLowerInvariant() }
    }
}

function Test-CompleterCommand {
    param([string]$Name)
    return [bool](Get-Command -Name $Name -ErrorAction SilentlyContinue)
}

function Invoke-CompleterProbe {
    param([string]$Program, [string[]]$Arguments)
    try {
        $out = & $Program @Arguments 2>$null | Out-String
        if ($LASTEXITCODE -eq 0 -and $out -and -not ($out -match '^(DESCRIPTION|USAGE)')) {
            return $out
        }
    } catch { }
    return $null
}

function Get-CompleterNativeSpec {
    param([string]$Shell)
    $subs  = @('upgrade','update','uninstall','acp','api','debug','auth','mcp','plugin','models','stats','mini','run','session','service','reload','pair','serve')
    $flags = @('--help','--version','--wizard','--completions','--log-level','--print-logs','--standalone','--server','--auto','--continue','--session','--prompt')
    if ($Shell -eq 'nu' -or $Shell -eq 'nushell') {
        $nuSubs  = ($subs  | ForEach-Object { "'$_'" }) -join ', '
        $nuFlags = ($flags | ForEach-Object { "'$_'" }) -join ', '
        return (@(
            '# Generated by completer: opencode native spec for nushell',
            'def "opencode subcommands" [] { [' + $nuSubs + '] }',
            'def "opencode flags" [] { [' + $nuFlags + '] }'
        ) -join [Environment]::NewLine)
    }
    $pySubs  = ($subs  | ForEach-Object { "'$_'" }) -join ', '
    $pyFlags = ($flags | ForEach-Object { "'$_'" }) -join ', '
    return (@(
        '# Generated by completer: opencode native spec for xonsh',
        '_opencode_subcommands = [' + $pySubs + ']',
        '_opencode_flags = [' + $pyFlags + ']'
    ) -join [Environment]::NewLine)
}

function Get-CompleterNativePowerShellSpec {
    param([string]$Program)
    $name = $Program -replace "'", "''"
    # Native, fully lazy PowerShell scaffold. Registering a completer is cheap;
    # the scriptblock only runs on Tab, so startup cost stays at zero.
    return (@(
        '# Generated by completer: native PowerShell completion scaffold',
        '# Program: ' + $Program,
        'if (Get-Module -ListAvailable -Name PSReadLine) {',
        '    Set-PSReadLineKeyHandler -Key Tab -Function MenuComplete',
        '}',
        "Register-ArgumentCompleter -Native -CommandName '$name' -ScriptBlock {",
        '    param($wordToComplete, $commandAst, $cursorPosition)',
        '    # Lazy native hook: no external command runs at load or registration.',
        '    # Defer to any provider-specific completer the tool registers itself.',
        '    return',
        '}'
    ) -join [Environment]::NewLine)
}

function Get-CompleterProgramOutput {
    param([string]$Program, [string]$Shell, [string]$Token)

    # opencode publishes completions via `opencode --completions <token>`; it has
    # no `completion` subcommand. Handle it explicitly, and first.
    if ($Program -eq 'opencode' -and (Test-CompleterCommand 'opencode')) {
        $r = Invoke-CompleterProbe -Program 'opencode' -Arguments @('--completions', $Token)
        if ($r) { return $r }
        if ($Shell -eq 'nu' -or $Shell -eq 'nushell' -or $Shell -eq 'xonsh') {
            return Get-CompleterNativeSpec -Shell $Shell
        }
    }

    # Generic acquisition order from the SPEC.
    $probes = @(
        @('completion', '--shell', $Token),
        @('completion', '-s', $Token),
        @('completion', $Token),
        @('completions', $Token),
        @('--generate-completion', $Token),
        @('--completions', $Token)
    )
    foreach ($probeArgs in $probes) {
        if (Test-CompleterCommand $Program) {
            $r = Invoke-CompleterProbe -Program $Program -Arguments $probeArgs
            if ($r) { return $r }
        }
    }

    # carapace can emit a single-completer script for indexed commands.
    if (Test-CompleterCommand 'carapace') {
        $r = Invoke-CompleterProbe -Program 'carapace' -Arguments @($Program, $Token)
        if ($r) { return $r }
    }

    # Last-resort native fallbacks (native APIs only, fully lazy).
    if ($Program -eq 'opencode' -and ($Shell -eq 'nu' -or $Shell -eq 'nushell' -or $Shell -eq 'xonsh')) {
        return Get-CompleterNativeSpec -Shell $Shell
    }
    if ($Shell -eq 'pwsh' -or $Shell -eq 'powershell') {
        return Get-CompleterNativePowerShellSpec -Program $Program
    }
    return $null
}

function Backup-CompleterFile {
    param([string]$Path)
    if (Test-Path -LiteralPath $Path) {
        $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
        $dest = "$Path.bak.$stamp"
        Copy-Item -LiteralPath $Path -Destination $dest -Force
        Write-Host "  backup -> $dest" -ForegroundColor DarkGray
    }
}

function Get-CompleterMainConfig {
    param([string]$Shell)
    $cfg = $env:XDG_CONFIG_HOME
    if (-not $cfg) { $cfg = Join-Path $HOME '.config' }
    switch ($Shell.ToLowerInvariant()) {
        { $_ -eq 'pwsh' -or $_ -eq 'powershell' } {
            if ($PROFILE -and $PROFILE.CurrentUserAllHosts) { return $PROFILE.CurrentUserAllHosts }
            return (Join-Path $HOME 'Documents\PowerShell\profile.ps1')
        }
        { $_ -eq 'nu' -or $_ -eq 'nushell' } {
            $alt = Join-Path $cfg 'shells\nushell\config.nu'
            if (Test-Path -LiteralPath $alt) { return $alt }
            return (Join-Path $cfg 'nushell\config.nu')
        }
        'xonsh' {
            $alt = Join-Path $HOME '.xonshrc'
            if (Test-Path -LiteralPath $alt) { return $alt }
            return (Join-Path $cfg 'xonsh\.xonshrc')
        }
        'bash' { return (Join-Path $HOME '.bashrc') }
        'zsh'  { return (Join-Path $HOME '.zshrc') }
        'fish' { return (Join-Path $cfg 'fish\config.fish') }
        'sh'   { return (Join-Path $HOME '.profile') }
        default { return (Join-Path $cfg "completer\$Shell-completion.$(Get-CompleterExtension $Shell)") }
    }
}

function Get-CompleterLoadLine {
    param([string]$File, [string]$Shell)
    $fwd = $File -replace '\\','/'
    switch ($Shell.ToLowerInvariant()) {
        { $_ -eq 'pwsh' -or $_ -eq 'powershell' } { return ". '$($File -replace "'", "''")'" }
        { $_ -eq 'nu' -or $_ -eq 'nushell' }      { return "source '$($fwd -replace "'", "''")'" }
        'xonsh' { return "execx(open('$($fwd -replace "'", "''")').read(), 'exec', __xonsh__.ctx)" }
        default { return "source '$($fwd -replace "'", "''")'" }
    }
}

function Add-CompleterSourceLink {
    param([string]$Config, [string]$File, [string]$Shell)
    if (-not $Config -or -not (Test-Path -LiteralPath $Config)) { return }
    $content = Get-Content -LiteralPath $Config -Raw
    if (-not $content) { $content = '' }
    $key = "${Shell}:$([IO.Path]::GetFileName($File))"
    $begin = "# >>> completer:$key >>>"
    $end   = "# <<< completer:$key <<<"
    if ($content.Contains($begin)) { return }   # idempotent: guarded marker block
    Backup-CompleterFile -Path $Config
    $block = (@('', $begin, (Get-CompleterLoadLine -File $File -Shell $Shell), $end, '') -join [Environment]::NewLine)
    Add-Content -LiteralPath $Config -Value $block -Encoding UTF8
    Write-Host "  linked -> $Config" -ForegroundColor Green
}

function Add-CompleterCompletionBlock {
    param([string]$Path, [string]$Program, [string]$Shell, [string]$Text)
    $begin = "# >>> completer:${Program}:${Shell} >>>"
    $end   = "# <<< completer:${Program}:${Shell} <<<"
    $stamp = "# generated: $(Get-Date -Format o)"
    $block = (@($begin, $stamp, '', $Text.TrimEnd(), '', $end, '') -join [Environment]::NewLine)
    $existing = ''
    if (Test-Path -LiteralPath $Path) { $existing = Get-Content -LiteralPath $Path -Raw }
    if (-not $existing) { $existing = '' }
    if ($existing.Contains($begin)) {
        # Refresh the one managed block in place (one program per file).
        Backup-CompleterFile -Path $Path
        Set-Content -LiteralPath $Path -Value $block -Encoding UTF8
    } else {
        if ($existing) { Backup-CompleterFile -Path $Path }
        Add-Content -LiteralPath $Path -Value $block -Encoding UTF8
    }
}

function Add-CompleterAlias {
    param([Parameter(Mandatory)][string]$Name, [Parameter(Mandatory)][string]$Value)
    Ensure-CompleterState
    if (-not (Test-Path -LiteralPath $script:CompleterAliasFile)) {
        $parent = Split-Path -Parent $script:CompleterAliasFile
        if ($parent -and -not (Test-Path -LiteralPath $parent)) {
            New-Item -ItemType Directory -Path $parent -Force | Out-Null
        }
        Set-Content -LiteralPath $script:CompleterAliasFile -Value '# alias.ps1 - managed by completer; dot-source from your profile' -Encoding UTF8
    }
    Backup-CompleterFile -Path $script:CompleterAliasFile
    $pattern = '(?i)^\s*Set-Alias\s+-Name\s+' + [regex]::Escape($Name) + '(?=\s|$)'
    $lines = @(Get-Content -LiteralPath $script:CompleterAliasFile | Where-Object { $_ -notmatch $pattern })
    $lines += "Set-Alias -Name $Name -Value $Value -Force"
    Set-Content -LiteralPath $script:CompleterAliasFile -Value $lines -Encoding UTF8
    Write-Host "  alias '$Name' -> '$Value' in $script:CompleterAliasFile" -ForegroundColor Green
}

function Remove-CompleterAlias {
    param([Parameter(Mandatory)][string]$Name)
    Ensure-CompleterState
    if (-not (Test-Path -LiteralPath $script:CompleterAliasFile)) { return }
    $pattern = '(?i)^\s*Set-Alias\s+-Name\s+' + [regex]::Escape($Name) + '(?=\s|$)'
    $lines = @(Get-Content -LiteralPath $script:CompleterAliasFile | Where-Object { $_ -notmatch $pattern })
    Backup-CompleterFile -Path $script:CompleterAliasFile
    Set-Content -LiteralPath $script:CompleterAliasFile -Value $lines -Encoding UTF8
    Write-Host "  alias '$Name' removed" -ForegroundColor Green
}

function Update-CompleterCarapace {
    Ensure-CompleterState
    if (-not (Test-CompleterCommand 'carapace')) { Write-Warning 'carapace not found; nothing to update'; return }
    Write-Host 'Refreshing carapace indexes (native carapace CLI)...' -ForegroundColor Cyan
    $null = & carapace --clear-cache 2>$null
    $list = (& carapace --list 2>$null | Measure-Object -Line).Lines
    Write-Host "  indexed completers: $list" -ForegroundColor DarkGray
    foreach ($sh in @('bash','zsh','fish','powershell','nushell','xonsh')) {
        $out = Join-Path $script:CompleterCompletions "carapace-$sh-init.$(Get-CompleterExtension $sh)"
        $res = & carapace _carapace $sh 2>$null | Out-String
        if ($res -and $res.Trim()) {
            Backup-CompleterFile -Path $out
            Set-Content -LiteralPath $out -Value $res -Encoding UTF8
            Write-Host "  indexed: $sh -> $out" -ForegroundColor DarkGray
        }
    }
    Write-Host 'Carapace index refreshed.' -ForegroundColor Green
}

function Add-CompleterZoxide {
    param([string]$Shell)
    Ensure-CompleterState
    if (-not (Test-CompleterShell $Shell)) { Write-Warning "Unsupported zoxide shell '$Shell'"; return }
    if (-not (Test-CompleterCommand 'zoxide')) { Write-Warning 'zoxide not found; nothing to do'; return }
    $token = Get-CompleterShellToken $Shell
    $editor = @()
    if ($Shell -eq 'pwsh' -or $Shell -eq 'powershell') { $editor = @('--cmd','cd') }
    $out = Join-Path $script:CompleterCompletions "$Shell-zoxide-init.$(Get-CompleterExtension $Shell)"
    if ($editor.Count -gt 0) { $res = & zoxide init $token @editor 2>$null | Out-String }
    else                     { $res = & zoxide init $token 2>$null | Out-String }
    if (-not $res -or -not $res.Trim()) { Write-Warning "zoxide produced no init for $Shell"; return }
    Backup-CompleterFile -Path $out
    Set-Content -LiteralPath $out -Value $res -Encoding UTF8
    Write-Host "  wrote zoxide init -> $out" -ForegroundColor Green
    Add-CompleterSourceLink -Config (Get-CompleterMainConfig $Shell) -File $out -Shell $Shell
}

function completer {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory, Position=0)][string]$Action,
        [Parameter(ValueFromRemainingArguments=$true)][string[]]$Program,
        [string]$LinkMode = 'Source',
        [switch]$NoLink
    )

    # ValueFromRemainingArguments binds every trailing token to $Program (needed
    # for `completer alias add <name> <value>`); restore the documented default.
    if (-not $Program -or $Program.Count -eq 0) { $Program = @('opencode') }
    Initialize-CompleterState
    if (-not (Test-Path -LiteralPath $script:CompleterCompletions)) {
        New-Item -ItemType Directory -Path $script:CompleterCompletions -Force | Out-Null
    }

    switch ($Action.ToLowerInvariant()) {
        'list' {
            if (Test-Path -LiteralPath $script:CompleterCompletions) {
                Get-ChildItem -LiteralPath $script:CompleterCompletions | Select-Object Name,Length,LastWriteTime
            }
            return
        }
        'zoxide' {
            $defaultPrograms = ($Program.Count -eq 1 -and $Program[0] -eq 'opencode')
            if ($defaultPrograms) { $targets = @('pwsh','nu','xonsh') } else { $targets = $Program }
            foreach ($z in $targets) { Add-CompleterZoxide -Shell $z }
            return
        }
        'update' {
            $target = ''
            if ($Program -and $Program.Count -gt 0) { $target = [string]$Program[0] }
            if ($target.ToLowerInvariant() -eq 'carapace') { Update-CompleterCarapace }
            else { Write-Warning "Unknown update target '$target'. Try: completer update carapace" }
            return
        }
        'alias' {
            $sub = ''
            if ($Program -and $Program.Count -gt 0) { $sub = ([string]$Program[0]).ToLowerInvariant() }
            switch ($sub) {
                'add' {
                    if (-not $Program -or $Program.Count -lt 3) { Write-Warning 'usage: completer alias add <name> <value>'; break }
                    Add-CompleterAlias -Name ([string]$Program[1]) -Value (($Program[2..($Program.Count-1)]) -join ' ')
                }
                'remove' {
                    if (-not $Program -or $Program.Count -lt 2) { Write-Warning 'usage: completer alias remove <name>'; break }
                    Remove-CompleterAlias -Name ([string]$Program[1])
                }
                default { Write-Host 'usage: completer alias add <name> <value> | remove <name>' }
            }
            return
        }
        default {
            $shell = $Action.ToLowerInvariant()
            if (-not (Test-CompleterShell $shell)) {
                Write-Warning "Unknown action/shell '$Action'. Try: list | alias | update | zoxide | <shell>"
                return
            }
            $token = Get-CompleterShellToken $shell
            $ext = Get-CompleterExtension $shell
            foreach ($prog in $Program) {
                Write-Host "Generating $prog completions for $shell..." -ForegroundColor Cyan
                $out = Join-Path $script:CompleterCompletions "$shell-$prog-completion.$ext"
                $text = Get-CompleterProgramOutput -Program $prog -Shell $shell -Token $token
                if (-not $text -or -not $text.Trim()) { Write-Warning "No completion for '$prog' ($shell)"; continue }
                Add-CompleterCompletionBlock -Path $out -Program $prog -Shell $shell -Text $text
                Write-Host "  wrote -> $out" -ForegroundColor Green
                if (-not $NoLink) {
                    if ($LinkMode -eq 'Symlink') {
                        $config = Get-CompleterMainConfig $shell
                        $linkDir = Split-Path -Parent $config
                        $link = Join-Path $linkDir "$shell-$prog-completion.$ext"
                        try {
                            if ($linkDir -and -not (Test-Path -LiteralPath $linkDir)) { New-Item -ItemType Directory -Path $linkDir -Force | Out-Null }
                            if (Test-Path -LiteralPath $link) { Backup-CompleterFile -Path $link; Remove-Item -LiteralPath $link -Force }
                            $null = New-Item -ItemType SymbolicLink -Path $link -Target $out -Force
                            Write-Host "  symlink -> $link" -ForegroundColor Green
                            Add-CompleterSourceLink -Config $config -File $link -Shell $shell
                        } catch {
                            Write-Warning "Symlink failed: $_"
                            Add-CompleterSourceLink -Config $config -File $out -Shell $shell
                        }
                    } else {
                        Add-CompleterSourceLink -Config (Get-CompleterMainConfig $shell) -File $out -Shell $shell
                    }
                }
            }
        }
    }
}
